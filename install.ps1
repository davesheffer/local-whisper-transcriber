# Meeting Recorder & Transcriber - Windows installer (per user, no admin needed).
#   - installs Python + Node dependencies and builds the app
#   - generates launchers in .\launcher\ with this machine's python/node paths
#   - starts the server hidden at every login (Startup folder shortcut)
#   - adds a desktop shortcut that opens the app in its own window
# Re-run any time to update (e.g. after git pull). Undo with uninstall.ps1.
param(
    [switch]$Gpu,          # force-install CUDA libraries
    [switch]$NoGpu,        # skip CUDA libraries even if an NVIDIA GPU is present
    [switch]$NoAutostart,  # don't start the server at login
    [switch]$NoDesktopShortcut
)
$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
$Port = 5000
$AppUrl = "http://localhost:$Port/"
$AppName = 'Meeting Transcriber'

function Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Ok($msg) { Write-Host "    $msg" -ForegroundColor Green }
function Invoke-Checked([string]$what, [scriptblock]$cmd) {
    & $cmd
    if ($LASTEXITCODE -ne 0) { throw "$what failed (exit $LASTEXITCODE)" }
}
function Find-Exe($name, $hint) {
    $c = Get-Command $name -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $c) { throw "$name not found on PATH. $hint" }
    return $c.Source
}

# --- prerequisites ------------------------------------------------------------
Step 'Checking prerequisites'
$Python = Find-Exe 'python' 'Install Python 3.9+ from https://www.python.org/downloads/ and tick "Add python.exe to PATH".'
if ($Python -like '*\WindowsApps\*') {
    throw 'Only the Microsoft Store "python" alias was found. Install Python from python.org (tick "Add to PATH") and re-run.'
}
$Node = Find-Exe 'node' 'Install Node.js LTS from https://nodejs.org/'
$Npm = Find-Exe 'npm' 'Install Node.js LTS from https://nodejs.org/'
Ok "python: $Python ($(& $Python --version 2>&1))"
Ok "node:   $Node ($(& $Node --version))"

# --- dependencies -------------------------------------------------------------
Step 'Installing Python packages (faster-whisper)'
Invoke-Checked 'pip install' { & $Python -m pip install --disable-pip-version-check -r "$Root\server\requirements.txt" }

$hasNvidia = [bool](Get-Command nvidia-smi -ErrorAction SilentlyContinue)
if ($Gpu -or ($hasNvidia -and -not $NoGpu)) {
    Step 'Installing NVIDIA CUDA libraries for GPU transcription'
    Invoke-Checked 'pip install (GPU)' { & $Python -m pip install --disable-pip-version-check -r "$Root\server\requirements-gpu.txt" }
} else {
    Ok 'No NVIDIA GPU detected - using CPU (pass -Gpu to force CUDA libraries).'
}

Step 'Installing Node packages'
Push-Location $Root
try { Invoke-Checked 'npm install (app)' { & $Npm install --no-audit --no-fund } } finally { Pop-Location }
Push-Location "$Root\server"
try { Invoke-Checked 'npm install (server)' { & $Npm install --no-audit --no-fund } } finally { Pop-Location }

Step 'Building the app'
Push-Location $Root
try { Invoke-Checked 'npm run build' { & $Npm run build } } finally { Pop-Location }

# --- launchers ----------------------------------------------------------------
Step 'Writing launchers'
$Launcher = Join-Path $Root 'launcher'
New-Item -ItemType Directory -Force -Path $Launcher | Out-Null

$browser = $null
foreach ($exe in 'chrome.exe', 'msedge.exe') {
    foreach ($hive in 'HKCU', 'HKLM') {
        $key = "${hive}:\SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\$exe"
        $p = (Get-ItemProperty -Path $key -ErrorAction SilentlyContinue).'(default)'
        if ($p -and (Test-Path $p)) { $browser = $p; break }
    }
    if ($browser) { break }
}
if (-not $browser) { throw 'Google Chrome or Microsoft Edge is required (recording uses Chrome screen/tab audio sharing).' }
Ok "browser: $browser"

function VbsStr($s) { '"' + ($s -replace '"', '""') + '"' }

# start-server.vbs: run the Node server hidden, logging to server\server.log
$startServer = @"
' Generated by install.ps1 - starts the transcription server without a window.
Set sh = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
logPath = $(VbsStr "$Root\server\server.log")
If fso.FileExists(logPath) Then
  If fso.GetFile(logPath).Size > 5242880 Then fso.CopyFile logPath, logPath & ".old", True : fso.DeleteFile logPath
End If
Set env = sh.Environment("Process")
env("PYTHON_BIN") = $(VbsStr $Python)
env("RECORDINGS_DIR") = sh.SpecialFolders("MyDocuments") & "\Meeting Recordings"
sh.CurrentDirectory = $(VbsStr "$Root\server")
q = Chr(34)
' cmd /c ""node.exe" server.js >> "log" 2>&1"  (outer quotes are stripped by cmd)
sh.Run "cmd /c " & q & q & $(VbsStr $Node) & q & " server.js >> " & q & logPath & q & " 2>&1" & q, 0, False
"@
Set-Content -Path "$Launcher\start-server.vbs" -Value $startServer -Encoding ASCII

# open-app.vbs: make sure the server is up, then open the app window
$openApp = @"
' Generated by install.ps1 - starts the server if needed, then opens the app.
Set sh = CreateObject("WScript.Shell")
Function ServerUp()
  On Error Resume Next
  Set http = CreateObject("MSXML2.ServerXMLHTTP.6.0")
  http.setTimeouts 1000, 1000, 1000, 1000
  http.Open "GET", "http://127.0.0.1:$Port/api/health", False
  http.Send
  ServerUp = (Err.Number = 0 And http.Status = 200)
  On Error GoTo 0
End Function
q = Chr(34)
If Not ServerUp() Then
  sh.Run "wscript.exe " & q & $(VbsStr "$Launcher\start-server.vbs") & q, 0, False
  For i = 1 To 30
    WScript.Sleep 500
    If ServerUp() Then Exit For
  Next
End If
sh.Run q & $(VbsStr $browser) & q & " --app=$AppUrl", 1, False
"@
Set-Content -Path "$Launcher\open-app.vbs" -Value $openApp -Encoding ASCII
Ok "launchers in $Launcher"

# --- shortcuts ----------------------------------------------------------------
$shell = New-Object -ComObject WScript.Shell
$wscript = Join-Path $env:WINDIR 'System32\wscript.exe'
$icon = "$Root\public\app.ico"

function New-Shortcut($path, $target, $arguments, $description) {
    $lnk = $shell.CreateShortcut($path)
    $lnk.TargetPath = $target
    $lnk.Arguments = $arguments
    $lnk.WorkingDirectory = $Root
    $lnk.IconLocation = $icon
    $lnk.Description = $description
    $lnk.Save()
}

$startupLnk = Join-Path ([Environment]::GetFolderPath('Startup')) "$AppName Server.lnk"
if ($NoAutostart) {
    if (Test-Path $startupLnk) { Remove-Item $startupLnk }
    Ok 'Autostart skipped.'
} else {
    Step 'Enabling autostart at login'
    New-Shortcut $startupLnk $wscript "`"$Launcher\start-server.vbs`"" 'Starts the local Whisper transcription server'
    Ok $startupLnk
}

if (-not $NoDesktopShortcut) {
    Step 'Creating desktop shortcut'
    $desktopLnk = Join-Path ([Environment]::GetFolderPath('Desktop')) "$AppName.lnk"
    New-Shortcut $desktopLnk $wscript "`"$Launcher\open-app.vbs`"" 'Record meetings and transcribe them locally'
    Ok $desktopLnk
}

# --- (re)start the server -----------------------------------------------------
Step 'Starting the server'
$listener = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
if ($listener) {
    $proc = Get-Process -Id $listener.OwningProcess -ErrorAction SilentlyContinue
    $cmdLine = (Get-CimInstance Win32_Process -Filter "ProcessId=$($listener.OwningProcess)" -ErrorAction SilentlyContinue).CommandLine
    if ($proc -and $proc.ProcessName -eq 'node' -and $cmdLine -like '*server.js*') {
        Ok "Restarting the running server (pid $($proc.Id)) to load the new version"
        Stop-Process -Id $proc.Id -Force
        Start-Sleep -Seconds 1
    } else {
        throw "Port $Port is used by another program ($($proc.ProcessName), pid $($listener.OwningProcess)). Close it and re-run."
    }
}
Start-Process -FilePath $wscript -ArgumentList "`"$Launcher\open-app.vbs`""

Write-Host "`nDone." -ForegroundColor Green
Write-Host "  App:        $AppUrl  (desktop shortcut: '$AppName')"
Write-Host "  Recordings: Documents\Meeting Recordings"
Write-Host "  Server log: $Root\server\server.log"
Write-Host "  Tip: in the app window use the browser menu > 'Install' to pin it to the taskbar / Start menu."
